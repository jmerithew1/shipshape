#!/usr/bin/env node
// AST-based type-safety violation counter. MEASURE ONLY - never writes to source.
// Usage: node count-types.mjs <repoRoot>
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const ROOT = process.argv[2];
// resolve the repo's own typescript (script lives outside the repo)
const require = createRequire(path.join(ROOT, 'package.json'));
const ts = require('typescript');
const PKGS = ['api', 'web', 'shared'];
const EXCLUDE_DIRS = new Set(['node_modules', 'dist', 'build', '.git', 'coverage', '.turbo']);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (EXCLUDE_DIRS.has(e.name)) continue;
      walk(path.join(dir, e.name), out);
    } else if (/\.(ts|tsx)$/.test(e.name) && !/\.d\.ts$/.test(e.name)) {
      out.push(path.join(dir, e.name));
    }
  }
  return out;
}

// Generated files: emitted by a script, not hand-written. Detected by header marker or known generator output.
const GENERATED_RE = /^\s*(\/\/|\/\*)\s*(auto-?generated|generated by|do not edit|@generated)/im;
function isGenerated(file, text) {
  if (/generate-icon-types/.test(text.slice(0, 500))) return true;
  return GENERATED_RE.test(text.slice(0, 800));
}

function isTest(rel) {
  const p = rel.replace(/\\/g, '/');
  return /(^|\/)(__tests__|__mocks__|test|tests)\//.test(p) ||
         /\.(test|spec)\.(ts|tsx)$/.test(p) ||
         /(^|\/)setup\.ts$/.test(p) ||
         /(^|\/)test-utils?/.test(p);
}

const rows = [];

for (const pkg of PKGS) {
  const srcDir = path.join(ROOT, pkg, 'src');
  if (!fs.existsSync(srcDir)) continue;
  for (const file of walk(srcDir)) {
    const text = fs.readFileSync(file, 'utf8');
    const rel = path.relative(ROOT, file).replace(/\\/g, '/');
    const generated = isGenerated(file, text);
    const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ES2022, true,
      file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);

    const c = {
      any: 0, anyDetail: [],
      asUnsafe: 0, asUnsafeDetail: [],
      asConst: 0,
      asUnknownAs: 0,
      angleAssert: 0,
      nonNull: 0, nonNullDetail: [],
      tsIgnore: 0, tsExpectError: 0,
      satisfies: 0,
    };

    const line = (n) => sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;

    function visit(node) {
      // `any` keyword in a type position
      if (node.kind === ts.SyntaxKind.AnyKeyword) {
        c.any++;
        c.anyDetail.push(line(node));
      }
      // `x as T`
      if (ts.isAsExpression(node)) {
        const t = node.type;
        const isConst = ts.isTypeReferenceNode(t) && ts.isIdentifier(t.typeName) && t.typeName.escapedText === 'const';
        if (isConst) {
          c.asConst++;
        } else {
          c.asUnsafe++;
          c.asUnsafeDetail.push(line(node));
          // double assertion `x as unknown as T` - laundering, strictly worse
          if (ts.isAsExpression(node.expression) &&
              node.expression.type.kind === ts.SyntaxKind.UnknownKeyword) {
            c.asUnknownAs++;
          }
        }
      }
      // `<T>x` legacy assertion (TS files only)
      if (ts.isTypeAssertionExpression && ts.isTypeAssertionExpression(node)) {
        c.angleAssert++;
        c.asUnsafe++;
        c.asUnsafeDetail.push(line(node));
      }
      // `x satisfies T` - type-safe, tracked for contrast only
      if (ts.isSatisfiesExpression && ts.isSatisfiesExpression(node)) c.satisfies++;
      // postfix `x!` only. Prefix `!x` is PrefixUnaryExpression; `!==` is BinaryExpression.
      if (ts.isNonNullExpression(node)) {
        c.nonNull++;
        c.nonNullDetail.push(line(node));
      }
      ts.forEachChild(node, visit);
    }
    visit(sf);

    // ts-ignore / ts-expect-error: scan comment trivia across whole file
    for (const m of text.matchAll(/\/\/\s*@ts-ignore|\/\*\s*@ts-ignore/g)) c.tsIgnore++;
    for (const m of text.matchAll(/\/\/\s*@ts-expect-error|\/\*\s*@ts-expect-error/g)) c.tsExpectError++;

    rows.push({
      pkg, rel, generated, test: isTest(path.relative(path.join(ROOT, pkg), file)),
      loc: text.split('\n').length, ...c,
    });
  }
}

fs.writeFileSync(path.join(path.dirname(process.argv[1]), 'raw.json'), JSON.stringify(rows, null, 1));

const sum = (arr, k) => arr.reduce((a, r) => a + r[k], 0);
const KEYS = ['any', 'asUnsafe', 'nonNull', 'tsIgnore', 'tsExpectError', 'asConst', 'asUnknownAs', 'angleAssert', 'satisfies'];

function report(label, arr) {
  const parts = KEYS.map(k => `${k}=${sum(arr, k)}`).join('  ');
  console.log(`${label.padEnd(34)} files=${String(arr.length).padStart(4)}  ${parts}`);
}

const live = rows.filter(r => !r.generated);
console.log('=== GRAND TOTAL (excl. generated) ===');
report('ALL', live);
console.log('\n=== BY PACKAGE / PROD vs TEST ===');
for (const pkg of PKGS) {
  const p = live.filter(r => r.pkg === pkg);
  report(`${pkg} TOTAL`, p);
  report(`  ${pkg} prod`, p.filter(r => !r.test));
  report(`  ${pkg} test`, p.filter(r => r.test));
}
console.log('\n=== GENERATED (excluded above) ===');
report('generated', rows.filter(r => r.generated));
for (const r of rows.filter(g => g.generated)) console.log('   ', r.rel);

console.log('\n=== TOP 20 FILES BY TOTAL VIOLATIONS (any + asUnsafe + nonNull + ts-ignore/expect) ===');
const scored = live.map(r => ({ ...r, total: r.any + r.asUnsafe + r.nonNull + r.tsIgnore + r.tsExpectError }))
  .filter(r => r.total > 0).sort((a, b) => b.total - a.total);
for (const r of scored.slice(0, 20)) {
  console.log(`${String(r.total).padStart(4)}  any=${String(r.any).padStart(3)} as=${String(r.asUnsafe).padStart(3)} nn=${String(r.nonNull).padStart(3)} ign=${r.tsIgnore + r.tsExpectError}  loc=${String(r.loc).padStart(4)}  ${r.test ? 'TEST' : 'PROD'}  ${r.rel}`);
}

console.log('\n=== TOP 15 PROD-ONLY FILES ===');
for (const r of scored.filter(r => !r.test).slice(0, 15)) {
  console.log(`${String(r.total).padStart(4)}  any=${String(r.any).padStart(3)} as=${String(r.asUnsafe).padStart(3)} nn=${String(r.nonNull).padStart(3)} ign=${r.tsIgnore + r.tsExpectError}  ${r.rel}`);
}
